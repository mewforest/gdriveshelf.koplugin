local H=require('tests/helper');local Core=require('core')
H.test('deep scan is explicitly gated and never starts in offline mode',function()
 local n=0;local c=setmetatable({settings={},state={},network=function()n=n+1 end},{__index=Core})
 assert(not c:deepScan({id='p'}));H.eq(n,0)
 c.settings.beta_thumbnails=true;c.settings.offline=true;assert(not c:deepScan({id='p'}));H.eq(n,0)
end)
H.test('cancelled recursive scan cannot enqueue late child folders or previews',function()
 local queued={};local c=setmetatable({settings={beta_thumbnails=true},state={deep_checked={},preview_attempts={}},jobs={cancel=function()end},network=function(_,key,work,done)queued[#queued+1]={key=key,done=done};return true end,emit=function()end,save=function()end},{__index=Core})
 c:deepScan({id='p'});H.eq(#queued,1);c:cancelDeepScan()
 queued[1].done({{id='child',name='Nested',is_folder=true},{id='book',name='1.cbz'}});H.eq(#queued,1)
end)
