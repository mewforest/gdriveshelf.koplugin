local I={}
function I.language()
 local ok,gt=pcall(require,'gettext')
 local language=ok and gt.current_lang
 if language==nil and G_reader_settings then language=G_reader_settings:readSetting('language')end
 return type(language)=='string' and language:lower():match('^ru') and 'ru' or 'en'
end
function I.gettext(message)
 if I.language()=='ru'then return ru[message]or message end
 return message
end
function I.format(message,...)return string.format(I.gettext(message),...)end
return I
